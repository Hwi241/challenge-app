const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const analysis=fs.readFileSync(path.join(root,'utils/recordRoomAnalysis.js'),'utf8');
const settings=fs.readFileSync(path.join(root,'utils/appSettings.js'),'utf8');
const settingsScreen=fs.readFileSync(path.join(root,'screens/SettingsScreen.js'),'utf8');
const Module=require('node:module');
const babel=require('@babel/core');
assert.match(settings,/recordRoomAnalysisPeriod: 'rolling30'/);
assert.match(settings,/getRecordRoomAnalysisPeriod/);
assert.match(settings,/setRecordRoomAnalysisPeriod/);
assert.match(settingsScreen,/최근 30일/);
assert.match(settingsScreen,/월간/);
assert.match(analysis,/mode === 'monthly'/);
assert.match(analysis,/Math\.min\(currentEnd\.getDate\(\), previousMonthLastDay\)/);
assert.match(analysis,/previousStart/);
assert.doesNotMatch(analysis,/const consistencyScore|const growthScore/);
const analysisFile=path.join(root,'utils/recordRoomAnalysis.js');
const transformed=babel.transformSync(analysis,{filename:analysisFile,plugins:['@babel/plugin-transform-modules-commonjs']}).code;
const analysisModule=new Module(analysisFile,module);
analysisModule.filename=analysisFile;
analysisModule.paths=Module._nodeModulePaths(path.dirname(analysisFile));
analysisModule._compile(transformed,analysisFile);
const {getRecordRoomAnalysisPeriods}=analysisModule.exports;
const rolling=getRecordRoomAnalysisPeriods(new Date(2026,9,5,12),'rolling30');
assert.equal(rolling.current.days,30);
assert.equal(rolling.current.start.getMonth(),8);
assert.equal(rolling.current.start.getDate(),6);
assert.equal(rolling.previous.end.getMonth(),8);
assert.equal(rolling.previous.end.getDate(),5);
const monthly=getRecordRoomAnalysisPeriods(new Date(2026,9,5,12),'monthly');
assert.equal(monthly.current.start.getDate(),1);
assert.equal(monthly.current.days,5);
assert.equal(monthly.previous.start.getMonth(),8);
assert.equal(monthly.previous.end.getDate(),5);
const monthEnd=getRecordRoomAnalysisPeriods(new Date(2026,2,31,12),'monthly');
assert.equal(monthEnd.previous.end.getMonth(),1);
assert.equal(monthEnd.previous.end.getDate(),28);
console.log('record room period tests: PASS');
